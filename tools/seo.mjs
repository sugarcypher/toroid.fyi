#!/usr/bin/env node
// toroid.fyi · search-index hygiene: sitemap.xml, robots.txt, and the generated block in _headers
//
//   node tools/seo.mjs            # write sitemap.xml, robots.txt, and the _headers block
//   node tools/seo.mjs --check    # report what would change, write nothing
//
// Why: Search Console showed every .md source and .json data file as "Crawled - currently
// not indexed" — Google found the raw sources beside their rendered .html pages and treated
// them as thin duplicates. The fix tells Google which copy is the page:
//   • each .md with a rendered .html twin gets a Link rel="canonical" header to the clean URL
//   • .json data, schema files, and .md sources with no twin get X-Robots-Tag: noindex
//     (they still load normally for the pages and people that fetch them)
//   • the summary PDF points its canonical at its reader page
//   • sitemap.xml lists every real HTML page, so discovery no longer depends on raw links
// Run after render-md.mjs whenever documents are added, moved, or removed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ORIGIN = 'https://toroid.fyi';
const CHECK = process.argv.includes('--check');
const SKIP_DIRS = new Set(['.git', '.github', 'node_modules', 'vendor', 'tools']);
const REPO_DOCS = new Set(['README.md', 'DEPLOY.md', 'COLLAB.md', 'LICENSE.md']);
const BEGIN = '# BEGIN generated by tools/seo.mjs — do not edit by hand';
const END = '# END generated by tools/seo.mjs';

// Non-HTML files whose canonical is a reader page rather than themselves.
const CANONICAL_OVERRIDES = {
  '/matrix/circulatory_pressure_architectures_summary.pdf': '/research/circulatory-pressure/',
};

function walk(dir, out = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(ent.name)) continue;
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, out);
    else out.push('/' + path.relative(ROOT, p).split(path.sep).join('/'));
  }
  return out;
}

// Cloudflare Pages serves /a/index.html at /a/ and /a/b.html at /a/b (308 from the .html form).
const cleanUrl = rel => rel.endsWith('/index.html') ? rel.slice(0, -'index.html'.length)
  : rel.endsWith('.html') ? rel.slice(0, -'.html'.length) : rel;

const files = walk(ROOT).sort();
const has = new Set(files);
const isNoindexPage = rel => /<meta[^>]+name=["']robots["'][^>]+noindex/i.test(fs.readFileSync(path.join(ROOT, rel), 'utf8'));

// ---- sitemap.xml
const pages = files.filter(f => f.endsWith('.html') && f !== '/404.html' && !isNoindexPage(f)).map(cleanUrl);
const sitemap = '<?xml version="1.0" encoding="UTF-8"?>\n'
  + '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
  + pages.map(u => `  <url><loc>${ORIGIN}${u}</loc></url>`).join('\n')
  + '\n</urlset>\n';

// ---- robots.txt (Cloudflare's managed robots.txt, when on, is prepended to this at the edge)
const robots = 'User-agent: *\nAllow: /\n\nSitemap: ' + ORIGIN + '/sitemap.xml\n';

// ---- _headers block
const rules = [];
for (const f of files) {
  const base = path.posix.basename(f);
  if (f.endsWith('.md')) {
    if (REPO_DOCS.has(base) && f.split('/').length === 2) { rules.push([f, 'X-Robots-Tag: noindex']); continue; }
    const twin = f.slice(0, -3) + '.html';
    if (has.has(twin)) rules.push([f, `Link: <${ORIGIN}${cleanUrl(twin)}>; rel="canonical"`]);
    else rules.push([f, 'X-Robots-Tag: noindex']);
  } else if (f.endsWith('.json')) {
    rules.push([f, 'X-Robots-Tag: noindex']);
  } else if (CANONICAL_OVERRIDES[f]) {
    rules.push([f, `Link: <${ORIGIN}${CANONICAL_OVERRIDES[f]}>; rel="canonical"`]);
  }
}
const block = [BEGIN,
  '# Raw sources and data files: point Google at the rendered page, or keep them out of the index.',
  ...rules.flatMap(([p, h]) => [p, '  ' + h]), END].join('\n');

const headersPath = path.join(ROOT, '_headers');
const oldHeaders = fs.readFileSync(headersPath, 'utf8');
const stripped = oldHeaders.includes(BEGIN)
  ? oldHeaders.slice(0, oldHeaders.indexOf(BEGIN)).replace(/\s*$/, '') + oldHeaders.slice(oldHeaders.indexOf(END) + END.length)
  : oldHeaders;
const newHeaders = stripped.replace(/\s*$/, '') + '\n\n' + block + '\n';

const totalRules = (newHeaders.match(/^\/\S*/gm) || []).length;
if (totalRules > 100) { console.error(`_headers would have ${totalRules} rules; Cloudflare Pages allows 100.`); process.exit(1); }

const outputs = [['sitemap.xml', sitemap], ['robots.txt', robots], ['_headers', newHeaders]];
for (const [name, body] of outputs) {
  const p = path.join(ROOT, name);
  const same = fs.existsSync(p) && fs.readFileSync(p, 'utf8') === body;
  console.log(`${same ? 'unchanged' : CHECK ? 'would write' : 'wrote'}  ${name}`);
  if (!same && !CHECK) fs.writeFileSync(p, body);
}
console.log(`${pages.length} sitemap URLs · ${rules.length} generated header rules · ${totalRules}/100 total header rules`);
